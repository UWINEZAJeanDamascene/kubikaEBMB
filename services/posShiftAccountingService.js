const JournalService = require('./journalService');
const { DEFAULT_ACCOUNTS } = require('../constants/chartOfAccounts');

const POS_REVERSIBLE_SOURCE_TYPES = new Set(['pos_cash_movement', 'pos_shift_close']);
const MOVEMENT_COUNTERPARTS = Object.freeze({
  cash_in: Object.freeze({
    EXTRA_CHANGE: 'posCashInExtraChange',
    OWNER_TOP_UP: 'posCashInOwnerTopUp',
    OTHER: 'posCashInOther',
  }),
  cash_out: Object.freeze({
    SUPPLIER_PAYMENT: 'posCashOutSupplierPayment',
    DELIVERY: 'posCashOutDelivery',
    STAFF_ADVANCE: 'posCashOutStaffAdvance',
    CLEANING_SUPPLIES: 'posCashOutCleaningSupplies',
    OTHER: 'posCashOutOther',
  }),
});

function journalEntryId(entry) {
  const id = entry?._id || entry?.id;
  if (!id) throw new Error('JournalService did not return the POS journal entry ID.');
  return String(id);
}

async function mappedAccount(companyId, key) {
  const fallback = DEFAULT_ACCOUNTS[key];
  if (!fallback) throw new Error(`No default account is configured for ${key}.`);
  const accountCode = await JournalService.getMappedAccountCode(companyId, 'cash', key, fallback);
  if (!accountCode) throw new Error(`No ledger account is configured for ${key}.`);
  return accountCode;
}

async function postCashMovement({ tx, companyId, userId, movement }) {
  const registerCash = await mappedAccount(companyId, 'posRegisterCash');
  let debitAccount;
  let creditAccount;
  const reasonLabel = movement.reasonCode.replace(/_/g, ' ').toLowerCase();

  if (movement.type === 'cash_in') {
    debitAccount = registerCash;
    const key = MOVEMENT_COUNTERPARTS.cash_in[movement.reasonCode] || 'posCashInOther';
    creditAccount = await mappedAccount(companyId, key);
  } else if (movement.type === 'cash_out') {
    const key = MOVEMENT_COUNTERPARTS.cash_out[movement.reasonCode] || 'posCashOutOther';
    debitAccount = await mappedAccount(companyId, key);
    creditAccount = registerCash;
  } else if (movement.type === 'safe_drop') {
    debitAccount = await mappedAccount(companyId, 'posSafeCash');
    creditAccount = registerCash;
  } else {
    throw new TypeError(`Unsupported POS cash movement type: ${movement.type}`);
  }

  const description = movement.type === 'safe_drop'
    ? 'POS safe drop'
    : `POS ${movement.type.replace('_', ' ')} - ${reasonLabel}`;
  const entry = await JournalService.createEntry(companyId, userId, {
    date: movement.createdAt || new Date(),
    description,
    sourceType: 'pos_cash_movement',
    sourceId: movement.id,
    sourceReference: movement.id,
    lines: [
      JournalService.createDebitLine(debitAccount, movement.amount, description),
      JournalService.createCreditLine(creditAccount, movement.amount, description),
    ],
    isAutoGenerated: true,
    notes: movement.note || '',
    session: tx,
    skipBankTransactions: true,
  });
  return journalEntryId(entry);
}

async function postShiftVariance({
  tx,
  companyId,
  userId,
  shift,
  variance,
  reportNumber,
  date,
  sourceId = shift.id,
}) {
  if (variance === 0) return null;

  const registerCash = await mappedAccount(companyId, 'posRegisterCash');
  const description = `POS shift ${shift.shiftNumber} cash ${variance > 0 ? 'overage' : 'shortage'}`;
  const amount = Math.abs(variance);
  const varianceAccount = await mappedAccount(
    companyId,
    variance > 0 ? 'posCashOverShortIncome' : 'posCashOverShortExpense',
  );
  const lines = variance > 0
    ? [
      JournalService.createDebitLine(registerCash, amount, description),
      JournalService.createCreditLine(varianceAccount, amount, description),
    ]
    : [
      JournalService.createDebitLine(varianceAccount, amount, description),
      JournalService.createCreditLine(registerCash, amount, description),
    ];
  const entry = await JournalService.createEntry(companyId, userId, {
    date,
    description,
    sourceType: 'pos_shift_close',
    sourceId,
    sourceReference: `Z-${reportNumber}`,
    lines,
    isAutoGenerated: true,
    notes: shift.differenceReason || '',
    session: tx,
    skipBankTransactions: true,
  });
  return journalEntryId(entry);
}

async function reverseJournalEntry({ tx, companyId, userId, entryId, date = new Date(), reason }) {
  const locked = await tx.$queryRawUnsafe(
    'SELECT "id" FROM "journal_entries" WHERE "id" = $1 AND "company_id" = $2 FOR UPDATE',
    String(entryId),
    String(companyId),
  );
  if (!locked.length) {
    throw Object.assign(new Error('The POS journal entry was not found for this company.'), {
      code: 'POS_JOURNAL_ENTRY_NOT_FOUND',
    });
  }

  const original = await tx.journalEntry.findFirst({
    where: { id: String(entryId), companyId: String(companyId) },
    include: { lines: { orderBy: { lineOrder: 'asc' } } },
  });
  if (!original) {
    throw Object.assign(new Error('The POS journal entry was not found for this company.'), {
      code: 'POS_JOURNAL_ENTRY_NOT_FOUND',
    });
  }
  if (!POS_REVERSIBLE_SOURCE_TYPES.has(original.sourceType)) {
    throw Object.assign(new Error('Only POS cash movement and shift-close entries can be reversed here.'), {
      code: 'POS_JOURNAL_REVERSAL_INVALID',
    });
  }
  if (original.reversalOfId) {
    throw Object.assign(new Error('A POS reversal entry cannot itself be reversed.'), {
      code: 'POS_JOURNAL_REVERSAL_INVALID',
    });
  }
  if (original.reversed || original.reversalEntryId) {
    if (!original.reversalEntryId) {
      throw Object.assign(new Error('The original POS journal entry is marked reversed but has no reversal entry.'), {
        code: 'POS_JOURNAL_REVERSAL_INCOMPLETE',
      });
    }
    const reversal = await tx.journalEntry.findFirst({
      where: { id: original.reversalEntryId, companyId: String(companyId) },
      select: { id: true, sourceType: true, reversalOfId: true },
    });
    if (!reversal || reversal.sourceType !== 'pos_shift_reversal'
      || String(reversal.reversalOfId) !== String(original.id)) {
      throw Object.assign(new Error('The reversal for this POS journal entry is unavailable.'), {
        code: 'POS_JOURNAL_REVERSAL_INCOMPLETE',
      });
    }
    return { journalEntryId: reversal.id, replayed: true };
  }
  if (original.status !== 'posted' || !Array.isArray(original.lines) || original.lines.length < 2) {
    throw Object.assign(new Error('Only a posted POS journal entry can be reversed.'), {
      code: 'POS_JOURNAL_REVERSAL_INVALID',
    });
  }

  const entry = await JournalService.createEntry(companyId, userId, {
    date,
    description: reason || `Reversal of ${original.entryNumber || original.id}`,
    sourceType: 'pos_shift_reversal',
    sourceId: original.id,
    sourceReference: original.sourceReference || original.id,
    reversalOf: original.id,
    lines: original.lines.map((line) => ({
      accountCode: line.accountCode,
      accountName: line.accountName,
      description: reason || `Reversal of ${line.description || original.entryNumber || original.id}`,
      debit: Number(line.credit || 0),
      credit: Number(line.debit || 0),
      reference: line.reference || '',
    })),
    isAutoGenerated: true,
    notes: reason || '',
    session: tx,
    skipBankTransactions: true,
  });
  const reversalId = journalEntryId(entry);

  await tx.journalEntry.update({
    where: { id: String(original.id), companyId: String(companyId) },
    data: {
      reversedAt: date,
      reversedById: String(userId),
      reversalEntryId: reversalId,
    },
  });
  return { journalEntryId: reversalId, replayed: false };
}

module.exports = {
  postCashMovement,
  postShiftVariance,
  reverseJournalEntry,
};
